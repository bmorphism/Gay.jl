# ═══════════════════════════════════════════════════════════════════════════
# Husserlian Moment: The Phenomenological "Now"
# ═══════════════════════════════════════════════════════════════════════════

"""
Husserlian Moment: the living present with its temporal horizons.

Structure:
- Primal Impression (Urimpression): the immediate now
- Retention: just-past still held in consciousness
- Protention: anticipated just-future

Each moment carries chromatic identity for SPI tracking.
"""
struct HusserlianMoment{T}
    primal_impression::T      # The "now" data
    retention::Vector{T}      # Past moments still in awareness (sliding window)
    protention::Vector{T}     # Anticipated future (predictions)
    color::RGB{Float64}       # Chromatic identity of this moment
    timestamp::Float64        # Phenomenological time
end

function HusserlianMoment(data::T, rng::SplittableRandom; 
                          retention_depth::Int=3, 
                          protention_depth::Int=2) where T
    color = color_from_rng(split(rng))
    HusserlianMoment{T}(
        data,
        Vector{T}(),  # Initially empty retention
        Vector{T}(),  # Initially empty protention
        color,
        time()
    )
end

"""
Advance to next moment: current becomes retained, new becomes primal.
"""
function advance_moment(m::HusserlianMoment{T}, new_data::T, rng::SplittableRandom;
                        max_retention::Int=5) where T
    # Current primal becomes first retention
    new_retention = [m.primal_impression; m.retention[1:min(end, max_retention-1)]]
    
    # Protentions shift (first becomes primal expectation for comparison)
    new_protention = isempty(m.protention) ? T[] : m.protention[2:end]
    
    color = color_from_rng(split(rng))
    HusserlianMoment{T}(new_data, new_retention, new_protention, color, time())
end

# ═══════════════════════════════════════════════════════════════════════════
# Open Game: Compositional Game with Coutility
# ═══════════════════════════════════════════════════════════════════════════

"""
Open Game: a game played relative to an environment.

Following Ghani-Hedges-Winschel-Zahn (2016):
- Morphisms of a symmetric monoidal category
- Compose sequentially (;) and in parallel (⊗)
- Return coutility to the environment

Extended with Gay.jl chromatic identity.
"""
struct OpenGame{X, Y, R, S}
    # Play function: X → Y (forward pass)
    play::Function
    
    # Coplay function: X × R → S (backward pass, propagates coutility)
    coplay::Function
    
    # Best response function: X × R → Bool (Nash equilibrium check)
    best_response::Function
    
    # Chromatic identity
    color::RGB{Float64}
    seed::UInt64
end

"""
Coutility: utility generated by game and returned to environment.

This is the key concept enabling compositional equilibrium.
"""
struct Coutility{R}
    value::R
    color::RGB{Float64}  # Chromatic signature of this coutility
end

"""
Compose games sequentially: G ; H
"""
function compose_seq(G::OpenGame, H::OpenGame, rng::SplittableRandom)
    color = color_from_rng(split(rng))
    
    OpenGame(
        x -> H.play(G.play(x)),
        (x, r) -> G.coplay(x, H.coplay(G.play(x), r)),
        (x, r) -> G.best_response(x, H.coplay(G.play(x), r)) && 
                  H.best_response(G.play(x), r),
        color,
        G.seed ⊻ H.seed
    )
end

"""
Compose games in parallel: G ⊗ H
"""
function compose_par(G::OpenGame, H::OpenGame, rng::SplittableRandom)
    color = color_from_rng(split(rng))
    
    OpenGame(
        (x1, x2) -> (G.play(x1), H.play(x2)),
        ((x1, x2), (r1, r2)) -> (G.coplay(x1, r1), H.coplay(x2, r2)),
        ((x1, x2), (r1, r2)) -> G.best_response(x1, r1) && H.best_response(x2, r2),
        color,
        G.seed ⊻ H.seed
    )
end

