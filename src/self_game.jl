# 2-Para: Para(Para(Game)) for Nested Self-Reference
# ═══════════════════════════════════════════════════════════════════════════

"""
2-Para: double parameterization for nested self-reference.

Para(Para(Game)) where:
- Outer Para: parameterizes by "self-model" (how SELF sees SELF)
- Inner Para: parameterizes by "world-model" (how SELF sees world)

This enables:
- SELF observing SELF observing world
- Reafference at two levels
- Semantic closure requires both levels to be consistent
"""
struct TwoPara{P1, P2, G}
    outer_param::P1    # Self-model parameter
    inner_param::P2    # World-model parameter
    game::G            # Base game
    
    # Nested color structure
    outer_color::RGB{Float64}  # Color of self-model
    inner_color::RGB{Float64}  # Color of world-model
    combined_color::RGB{Float64}  # XOR combination
end

function TwoPara(outer::P1, inner::P2, game::G, rng::SplittableRandom) where {P1, P2, G}
    rng1, rng2 = split(rng), split(split(rng))
    outer_color = color_from_rng(rng1)
    inner_color = color_from_rng(rng2)
    
    # Combined via XOR on fingerprints (compositionally sound)
    # XOR is associative, commutative, self-inverse - safe for nested composition
    outer_fp = color_fingerprint(rng1)
    inner_fp = color_fingerprint(rng2)
    combined_fp = outer_fp ⊻ inner_fp
    combined = color_from_fingerprint(combined_fp)
    
    TwoPara(outer, inner, game, outer_color, inner_color, combined)
end

# Helper: extract fingerprint from RNG state
function color_fingerprint(rng::SplittableRandom)::UInt64
    # Use the RNG's internal state as fingerprint
    h = hash(rng)
    z = (h + 0x9E3779B97F4A7C15)
    z = (z ⊻ (z >> 30)) * 0xBF58476D1CE4E5B9
    z = (z ⊻ (z >> 27)) * 0x94D049BB133111EB
    z ⊻ (z >> 31)
end

# Helper: derive color from fingerprint (the canonical way)
function color_from_fingerprint(fp::UInt64)::RGB{Float64}
    z1 = (fp + 0x9E3779B97F4A7C15)
    z1 = (z1 ⊻ (z1 >> 30)) * 0xBF58476D1CE4E5B9
    z1 = (z1 ⊻ (z1 >> 27)) * 0x94D049BB133111EB
    r = (z1 ⊻ (z1 >> 31)) >> 56
    
    z2 = (z1 + 0x9E3779B97F4A7C15)
    z2 = (z2 ⊻ (z2 >> 30)) * 0xBF58476D1CE4E5B9
    z2 = (z2 ⊻ (z2 >> 27)) * 0x94D049BB133111EB
    g = (z2 ⊻ (z2 >> 31)) >> 56
    
    z3 = (z2 + 0x9E3779B97F4A7C15)
    z3 = (z3 ⊻ (z3 >> 30)) * 0xBF58476D1CE4E5B9
    z3 = (z3 ⊻ (z3 >> 27)) * 0x94D049BB133111EB
    b = (z3 ⊻ (z3 >> 31)) >> 56
    
    RGB(r / 255.0, g / 255.0, b / 255.0)
end

"""
Apply 2-Para: instantiate game with both parameter levels.
"""
function apply_2para(tp::TwoPara, self_action, world_state)
    # First apply inner (world-model) parameter
    world_view = apply_world_model(tp.inner_param, world_state)
    
    # Then apply outer (self-model) parameter
    self_view = apply_self_model(tp.outer_param, self_action, world_view)
    
    self_view
end

# Default implementations (override for specific games)
apply_world_model(param, state) = (param, state)
apply_self_model(param, action, world) = (param, action, world)

# ═══════════════════════════════════════════════════════════════════════════
# SELF GAME: The Complete Structure
# ═══════════════════════════════════════════════════════════════════════════

"""
SELF GAME: Husserlian Moment as Colorable Derangeable Open Game with 2-Para.

The complete structure for self-aware agents:
- HusserlianMoment: temporal structure of consciousness
- ColorableGame: chromatic identity for all states/actions
- DerangeableGame: no fixed points (always becoming)
- OpenGame: compositional with coutility
- TwoPara: nested self-reference
- Self-avoiding walk: no revisiting past states

Semantic closure = world model consistency with self-model.
"""
mutable struct SelfGame{X, A}
    moment::HusserlianMoment{X}
    colorable::ColorableGame{X, A, Float64}
    derangeable::DerangeableGame{X, A}
    two_para::TwoPara
    
    # Trajectory tracking for self-avoiding walk
    visited_states::Set{X}
    trajectory::Vector{X}
    trajectory_colors::Vector{RGB{Float64}}
    
    # Interaction network
    network::Dict{X, Vector{X}}  # Adjacency for random interaction structure
    
    seed::UInt64
    rng::SplittableRandom
end

function SelfGame(
    states::Vector{X}, 
    actions::Vector{A},
    utility::Function,
    transition::Function;
    seed::UInt64=GAY_SEED
) where {X, A}
    rng = SplittableRandom(seed)
    
    # Build colorable game
    colorable = ColorableGame(states, actions, utility, transition; seed=seed)
    
    # Make it derangeable
    derangeable = DerangeableGame(colorable)
    
    # Initial Husserlian moment
    moment = HusserlianMoment(first(states), rng)
    
    # 2-Para with identity parameters initially
    two_para = TwoPara(:self_model_0, :world_model_0, colorable, rng)
    
    # Random interaction network (small-world-ish)
    network = build_interaction_network(states, rng)
    
    SelfGame(
        moment, colorable, derangeable, two_para,
        Set{X}([first(states)]),
        [first(states)],
        [moment.color],
        network,
        seed, rng
    )
end

"""
Build random interaction network structure.
"""
function build_interaction_network(states::Vector{X}, rng::SplittableRandom) where X
    n = length(states)
    network = Dict{X, Vector{X}}()
    
    for s in states
        # Each state connects to ~log(n) random others
        k = max(1, Int(ceil(log2(n))))
        rng = split(rng)
        neighbors = X[]
        
        for _ in 1:k
            rng = split(rng)
            idx = 1 + (rand(rng, UInt) % n)
            neighbor = states[idx]
            if neighbor != s
                push!(neighbors, neighbor)
            end
        end
        
        network[s] = unique(neighbors)
    end
    
    network
end

