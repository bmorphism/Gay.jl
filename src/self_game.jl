# Self-Avoiding Random Walk
# ═══════════════════════════════════════════════════════════════════════════

"""
Self-avoiding random walk on interaction network.

SELF explores the network without revisiting states (self-avoiding).
Uses chromatic identity to track and verify the path.
"""
function self_avoiding_walk!(game::SelfGame, max_steps::Int=100)
    current = game.moment.primal_impression
    
    for step in 1:max_steps
        # Get neighbors not yet visited
        neighbors = get(game.network, current, eltype(game.trajectory)[])
        available = filter(n -> n ∉ game.visited_states, neighbors)
        
        if isempty(available)
            # Stuck: no unvisited neighbors (semantic closure reached or trapped)
            return (
                steps = step - 1,
                reason = :no_available_moves,
                trajectory = game.trajectory,
                colors = game.trajectory_colors,
                closure = semantic_closure_check(game)
            )
        end
        
        # Choose random available neighbor
        game.rng = split(game.rng)
        idx = 1 + (rand(game.rng, UInt) % length(available))
        next_state = available[idx]
        
        # Advance moment
        game.rng = split(game.rng)
        game.moment = advance_moment(game.moment, next_state, game.rng)
        
        # Update trajectory
        push!(game.visited_states, next_state)
        push!(game.trajectory, next_state)
        push!(game.trajectory_colors, game.moment.color)
        
        current = next_state
    end
    
    (
        steps = max_steps,
        reason = :max_steps_reached,
        trajectory = game.trajectory,
        colors = game.trajectory_colors,
        closure = semantic_closure_check(game)
    )
end

# ═══════════════════════════════════════════════════════════════════════════
# Semantic Closure: World Model Consistency
# ═══════════════════════════════════════════════════════════════════════════

"""
Check semantic closure: self-model and world-model consistency.

Semantic closure is achieved when:
1. Self-model correctly predicts own trajectory (reafference match)
2. World-model is consistent with observed transitions
3. 2-Para structure is coherent (outer and inner agree)

Returns closure measure in [0, 1] where 1 = perfect closure.
"""
function semantic_closure_check(game::SelfGame)
    n = length(game.trajectory)
    n < 2 && return 1.0
    
    # Measure 1: Reafference consistency
    # Compare trajectory colors with self-model expectation
    color_variance = 0.0
    for i in 2:n
        expected = game.two_para.combined_color
        actual = game.trajectory_colors[i]
        color_variance += color_distance(expected, actual)^2
    end
    reafference_score = exp(-color_variance / n)
    
    # Measure 2: Transition consistency
    # Check that derangement property holds (no fixed points)
    fixed_point_violations = 0
    for i in 2:n
        if game.trajectory[i] == game.trajectory[i-1]
            fixed_point_violations += 1
        end
    end
    transition_score = 1.0 - fixed_point_violations / (n - 1)
    
    # Measure 3: 2-Para coherence
    # Outer and inner colors should combine predictably
    expected_combined = RGB(
        abs(red(game.two_para.outer_color) - red(game.two_para.inner_color)),
        abs(green(game.two_para.outer_color) - green(game.two_para.inner_color)),
        abs(blue(game.two_para.outer_color) - blue(game.two_para.inner_color))
    )
    para_coherence = 1.0 - color_distance(expected_combined, game.two_para.combined_color)
    
    # Combine measures
    (reafference_score + transition_score + para_coherence) / 3
end

"""
Color distance.
"""
function color_distance(c1::RGB, c2::RGB)
    sqrt((red(c1) - red(c2))^2 + (green(c1) - green(c2))^2 + (blue(c1) - blue(c2))^2)
end

# ═══════════════════════════════════════════════════════════════════════════
# Play Self Game: Full Execution
# ═══════════════════════════════════════════════════════════════════════════

"""
Play the SELF GAME: self-avoiding walk toward semantic closure.

Returns the trajectory with chromatic identity and closure measure.
"""
function play_self_game!(
    game::SelfGame;
    max_steps::Int=100,
    closure_threshold::Float64=0.9
)
    result = self_avoiding_walk!(game, max_steps)
    
    (
        trajectory = result.trajectory,
        colors = result.colors,
        steps = result.steps,
        reason = result.reason,
        closure = result.closure,
        achieved_closure = result.closure >= closure_threshold,
        husserlian_moment = game.moment,
        two_para = game.two_para
    )
end

"""
Compute coutility: what SELF returns to environment.

Coutility flows backward through the game composition.
"""
function coutility(game::SelfGame)
    # Coutility is the semantic closure achieved, with chromatic signature
    closure = semantic_closure_check(game)
    
    Coutility(closure, game.moment.color)
end

# ═══════════════════════════════════════════════════════════════════════════
# Color from RNG
# ═══════════════════════════════════════════════════════════════════════════

function color_from_rng(rng::SplittableRandom)::RGB{Float64}
    r = rand(rng)
    g = rand(rng)
    b = rand(rng)
    
    max_c = max(r, g, b)
    min_c = min(r, g, b)
    if max_c > min_c
        scale = 1.0 / (max_c - min_c + 0.3)
        r = (r - min_c) * scale
        g = (g - min_c) * scale
        b = (b - min_c) * scale
    end
    
    RGB{Float64}(clamp(r, 0, 1), clamp(g, 0, 1), clamp(b, 0, 1))
end

