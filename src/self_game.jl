# Colorable Game: Games with Chromatic Identity
# ═══════════════════════════════════════════════════════════════════════════

"""
Colorable Game: every state and action carries chromatic identity.

Implements the Colorable protocol from Gay.jl.
"""
struct ColorableGame{X, A, U}
    states::Vector{X}
    actions::Vector{A}
    utility::Function  # (X, A) → U
    transition::Function  # (X, A) → X
    
    # Chromatic structure
    state_colors::Dict{X, RGB{Float64}}
    action_colors::Dict{A, RGB{Float64}}
    seed::UInt64
    rng::SplittableRandom
end

function ColorableGame(states, actions, utility, transition; seed::UInt64=GAY_SEED)
    rng = SplittableRandom(seed)
    
    state_colors = Dict(s => color_from_rng(split(rng)) for s in states)
    action_colors = Dict(a => color_from_rng(split(rng)) for a in actions)
    
    ColorableGame(
        collect(states), collect(actions),
        utility, transition,
        state_colors, action_colors,
        seed, rng
    )
end

"""
Get color of a state.
"""
state_color(G::ColorableGame, s) = get(G.state_colors, s, RGB(0.5, 0.5, 0.5))

"""
Get color of an action.
"""
action_color(G::ColorableGame, a) = get(G.action_colors, a, RGB(0.5, 0.5, 0.5))

# ═══════════════════════════════════════════════════════════════════════════
# Derangeable Game: No Fixed Points (Always Becoming)
# ═══════════════════════════════════════════════════════════════════════════

"""
Derangeable Game: game where no state maps to itself.

Every action must change the state (σ(s) ≠ s for all s).
This captures Husserl's insight that consciousness is always becoming.
"""
struct DerangeableGame{X, A}
    base_game::ColorableGame{X, A, Float64}
    derangement::Vector{Int}  # Permutation of state indices with no fixed points
end

"""
Create a derangeable game from a colorable game.

Ensures transition function has no fixed points via rejection sampling.
"""
function DerangeableGame(G::ColorableGame{X, A, Float64}) where {X, A}
    n = length(G.states)
    n < 2 && error("Need at least 2 states for derangeable game")
    
    # Generate derangement
    derangement = generate_derangement(n, G.seed)
    
    DerangeableGame(G, derangement)
end

"""
Generate a derangement (permutation with no fixed points).
"""
function generate_derangement(n::Int, seed::UInt64)
    rng_state = seed
    
    for attempt in 1:1000
        perm = collect(1:n)
        
        # Fisher-Yates shuffle
        for i in n:-1:2
            rng_state = mix64(rng_state)
            j = 1 + (rng_state % i)
            perm[i], perm[j] = perm[j], perm[i]
        end
        
        # Check for fixed points
        has_fixed = any(i -> perm[i] == i, 1:n)
        if !has_fixed
            return perm
        end
        
        rng_state = mix64(rng_state)
    end
    
    error("Failed to generate derangement")
end

function mix64(z::UInt64)
    z = (z ⊻ (z >> 30)) * 0xbf58476d1ce4e5b9
    z = (z ⊻ (z >> 27)) * 0x94d049bb133111eb
    z ⊻ (z >> 31)
end

"""
Apply derangement transition.
"""
function deranged_transition(G::DerangeableGame, state_idx::Int)
    G.derangement[state_idx]
end

