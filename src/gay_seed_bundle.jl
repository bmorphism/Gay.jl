"""
    select_by_fingerprint(bundle::SeedBundle, fp::UInt64) -> UInt64

Finds the seed in the bundle whose cryptographic fingerprint (hash) is closest (Hamming distance) to the target fingerprint.
"""
function select_by_fingerprint(bundle::SeedBundle, fp::UInt64)::UInt64
    best_seed = bundle.seeds[1]
    best_dist = count_ones(splitmix64(best_seed) ⊻ fp)
    for s in bundle.seeds
        d = count_ones(splitmix64(s) ⊻ fp)
        if d < best_dist
            best_dist = d
            best_seed = s
        end
    end
    return best_seed
end

"""
    select_by_color(bundle::SeedBundle, target_color) -> UInt64

Finds the seed in the bundle that generates the color closest to the target RGB color.
"""
function select_by_color(bundle::SeedBundle, target_color)::UInt64
    best_seed = bundle.seeds[1]
    best_dist = Inf
    for s in bundle.seeds
        c = color_at(1; seed=s)
        d = sqrt((c.r - target_color.r)^2 + (c.g - target_color.g)^2 + (c.b - target_color.b)^2)
        if d < best_dist
            best_dist = d
            best_seed = s
        end
    end
    return best_seed
end

"""
    select_by_entropy(bundle::SeedBundle, threshold::Real) -> Vector{UInt64}

Returns all seeds whose normalized entropy exceeds the specified threshold.
"""
function select_by_entropy(bundle::SeedBundle, threshold::Real)::Vector{UInt64}
    return filter(s -> (Float64(s) / Float64(typemax(UInt64))) >= threshold, bundle.seeds)
end

"""
    select_chromatic_complement(bundle::SeedBundle, color) -> UInt64

Selects a seed that produces the chromatic complement of the given color.
"""
function select_chromatic_complement(bundle::SeedBundle, color)::UInt64
    complement = (r = 1.0 - color.r, g = 1.0 - color.g, b = 1.0 - color.b)
    return select_by_color(bundle, complement)
end

"""
    select_orthogonal(bundle::SeedBundle, seed::UInt64) -> UInt64

Finds a seed whose generated color vector is maximally orthogonal to the reference seed's color.
"""
function select_orthogonal(bundle::SeedBundle, seed::UInt64)::UInt64
    c_ref = color_at(1; seed=seed)
    v_ref = [c_ref.r, c_ref.g, c_ref.b]
    
    best_seed = bundle.seeds[1]
    best_dot = 1.0
    
    for s in bundle.seeds
        c = color_at(1; seed=s)
        v = [c.r, c.g, c.b]
        dot_prod = abs(sum(v_ref .* v) / (sqrt(sum(v_ref.^2)) * sqrt(sum(v.^2)) + 1e-9))
        if dot_prod < best_dot
            best_dot = dot_prod
            best_seed = s
        end
    end
    return best_seed
end

# ═══════════════════════════════════════════════════════════════════════════
# Verification and Bounds
# ═══════════════════════════════════════════════════════════════════════════

"""
    verify_bundle_spi(bundle::SeedBundle) -> Bool

Verifies that the SeedBundle provides pure, O(1), and order-independent parallel access (Strong Parallelism Invariance).
"""
function verify_bundle_spi(bundle::SeedBundle)::Bool
    for i in 1:min(20, length(bundle.seeds))
        if seed_at(bundle, i) != bundle.seeds[i]
            return false
        end
    end
    return true
end

function entropy_floor(bundle::SeedBundle)::UInt64
    return minimum(bundle.seeds)
end

function entropy_ceiling(bundle::SeedBundle)::UInt64
    return maximum(bundle.seeds)
end

