"""
    create_locale_view(bundle::SeedBundle, range_indices::AbstractVector{Int}, locale_name::String) -> LocaleView

Creates a localized ordered view of the SeedBundle over specific indices.
"""
function create_locale_view(bundle::SeedBundle, range_indices::AbstractVector{Int}, locale_name::String)::LocaleView
    valid_indices = [mod1(idx, BUNDLE_SIZE) for idx in range_indices]
    LocaleView(bundle, valid_indices, locale_name)
end

"""
    locale_lookup(view::LocaleView, key::Integer) -> UInt64

Look up a seed within a LocaleView.
"""
function locale_lookup(view::LocaleView, key::Integer)::UInt64
    idx = mod1(key, length(view.indices))
    return seed_at(view.bundle, view.indices[idx])
end

"""
    locale_range(view::LocaleView) -> Vector{UInt64}

Returns the full sequence of seeds contained within the LocaleView.
"""
function locale_range(view::LocaleView)::Vector{UInt64}
    return [seed_at(view.bundle, idx) for idx in view.indices]
end

"""
    locale_predecessor(view::LocaleView, index::Integer) -> UInt64

Returns the previous seed in the LocaleView sequence.
"""
function locale_predecessor(view::LocaleView, index::Integer)::UInt64
    idx = mod1(index - 1, length(view.indices))
    return seed_at(view.bundle, view.indices[idx])
end

"""
    locale_successor(view::LocaleView, index::Integer) -> UInt64

Returns the next seed in the LocaleView sequence.
"""
function locale_successor(view::LocaleView, index::Integer)::UInt64
    idx = mod1(index + 1, length(view.indices))
    return seed_at(view.bundle, view.indices[idx])
end

