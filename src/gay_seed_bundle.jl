# Global World Seed Bundle Singleton
# ═══════════════════════════════════════════════════════════════════════════

const world_gay_seed_bundle_ref = Ref{SeedBundle}()

"""
    world_gay_seed_bundle() -> SeedBundle

Returns the global SeedBundle singleton representing the world's primary entropy state.
"""
function world_gay_seed_bundle()::SeedBundle
    if !isassigned(world_gay_seed_bundle_ref)
        world_gay_seed_bundle_ref[] = SeedBundle()
    end
    return world_gay_seed_bundle_ref[]
end

"""
    gay_seed(index::Integer) -> UInt64
    gay_seed(bundle::SeedBundle, index::Integer) -> UInt64

Returns a high-entropy seed from the global singleton or specified SeedBundle.
"""
function gay_seed(index::Integer)::UInt64
    return seed_at(world_gay_seed_bundle(), index)
end

function gay_seed(bundle::SeedBundle, index::Integer)::UInt64
    return seed_at(bundle, index)
end

