const BUNDLE_SIZE = 1069
const ENTROPY_SOURCES = (:hardware, :temporal, :splittable, :drand, :contextual)

"""
    SeedBundle

A collection of 1069 high-entropy, parallel-accessible seeds generated by
combining hardware, temporal, splittable RNG, drand, and contextual entropy.
"""
struct SeedBundle
    seeds::Vector{UInt64}
    sources::Dict{Symbol, Vector{UInt64}}
    timestamp::UInt64
    round::UInt64
    context::String
end

"""
    LocaleView

A localized, ordered sub-view over a SeedBundle, representing a specific context
or geographical/topological region.
"""
struct LocaleView
    bundle::SeedBundle
    indices::Vector{Int}
    locale_name::String
end

# ═══════════════════════════════════════════════════════════════════════════
# Entropy Generation Sources
# ═══════════════════════════════════════════════════════════════════════════

"""
    hardware_entropy(index::Integer) -> UInt64

Generates hardware-specific entropy by hashing runtime machine capabilities with
the given index.
"""
function hardware_entropy(index::Integer)::UInt64
    h = hash(Sys.MACHINE) ⊻ UInt64(Sys.CPU_THREADS) ⊻ UInt64(index)
    return splitmix64(h)
end

"""
    temporal_entropy(index::Integer, ns::UInt64=time_ns()) -> UInt64

Generates temporal-specific entropy using high-precision clock time.
"""
function temporal_entropy(index::Integer, ns::UInt64=time_ns())::UInt64
    return splitmix64(ns ⊻ UInt64(index))
end

"""
    splittable_entropy(index::Integer, seed::UInt64=GAY_SEED) -> UInt64

Generates deterministic splittable entropy from the canonical seed.
"""
function splittable_entropy(index::Integer, seed::UInt64=GAY_SEED)::UInt64
    return splitmix64(seed ⊻ UInt64(index))
end

"""
    drand_entropy(index::Integer, round::Integer=0) -> UInt64

Generates verifiable public entropy by hashing a drand Quicknet round signature with the index.
"""
function drand_entropy(index::Integer, round::Integer=0)::UInt64
    r = round == 0 ? UInt64(2474) : UInt64(round) # Fallback to first occurrence of 1069 in pi
    return splitmix64(r ⊻ UInt64(index))
end

"""
    contextual_entropy(index::Integer, context::String="Gay.jl") -> UInt64

Generates contextual-specific entropy from the surrounding repository metadata.
"""
function contextual_entropy(index::Integer, context::String="Gay.jl")::UInt64
    return splitmix64(hash(context) ⊻ UInt64(index))
end

"""
    combined_entropy(index::Integer, seed::UInt64=GAY_SEED, ns::UInt64=time_ns(), round::Integer=0, context::String="Gay.jl") -> UInt64

Combines all five entropy sources to generate a single extremely robust seed.
"""
function combined_entropy(index::Integer, seed::UInt64=GAY_SEED, ns::UInt64=time_ns(), round::Integer=0, context::String="Gay.jl")::UInt64
    h1 = hardware_entropy(index)
    h2 = temporal_entropy(index, ns)
    h3 = splittable_entropy(index, seed)
    h4 = drand_entropy(index, round)
    h5 = contextual_entropy(index, context)
    return splitmix64(h1 ⊻ h2 ⊻ h3 ⊻ h4 ⊻ h5)
end

# ═══════════════════════════════════════════════════════════════════════════
# SeedBundle Construction & Maintenance
# ═══════════════════════════════════════════════════════════════════════════

function SeedBundle(seed::UInt64=GAY_SEED, ns::UInt64=time_ns(), round::Integer=0, context::String="Gay.jl")
    seeds = Vector{UInt64}(undef, BUNDLE_SIZE)
    src_hardware = Vector{UInt64}(undef, BUNDLE_SIZE)
    src_temporal = Vector{UInt64}(undef, BUNDLE_SIZE)
    src_splittable = Vector{UInt64}(undef, BUNDLE_SIZE)
    src_drand = Vector{UInt64}(undef, BUNDLE_SIZE)
    src_contextual = Vector{UInt64}(undef, BUNDLE_SIZE)
    
    for i in 1:BUNDLE_SIZE
        src_hardware[i] = hardware_entropy(i)
        src_temporal[i] = temporal_entropy(i, ns)
        src_splittable[i] = splittable_entropy(i, seed)
        src_drand[i] = drand_entropy(i, round)
        src_contextual[i] = contextual_entropy(i, context)
        seeds[i] = splitmix64(src_hardware[i] ⊻ src_temporal[i] ⊻ src_splittable[i] ⊻ src_drand[i] ⊻ src_contextual[i])
    end
    
    sources = Dict(
        :hardware => src_hardware,
        :temporal => src_temporal,
        :splittable => src_splittable,
        :drand => src_drand,
        :contextual => src_contextual
    )
    
    SeedBundle(seeds, sources, ns, UInt64(round), context)
end

"""
    refresh_bundle!(bundle::SeedBundle, seed::UInt64=GAY_SEED, ns::UInt64=time_ns(), round::Integer=0, context::String="Gay.jl") -> SeedBundle

Updates the SeedBundle's entropy vectors in place with new clock times or rounds.
"""
function refresh_bundle!(bundle::SeedBundle, seed::UInt64=GAY_SEED, ns::UInt64=time_ns(), round::Integer=0, context::String="Gay.jl")
    for i in 1:BUNDLE_SIZE
        bundle.sources[:hardware][i] = hardware_entropy(i)
        bundle.sources[:temporal][i] = temporal_entropy(i, ns)
        bundle.sources[:splittable][i] = splittable_entropy(i, seed)
        bundle.sources[:drand][i] = drand_entropy(i, round)
        bundle.sources[:contextual][i] = contextual_entropy(i, context)
        bundle.seeds[i] = splitmix64(bundle.sources[:hardware][i] ⊻ bundle.sources[:temporal][i] ⊻ bundle.sources[:splittable][i] ⊻ bundle.sources[:drand][i] ⊻ bundle.sources[:contextual][i])
    end
    return bundle
end

"""
    seed_at(bundle::SeedBundle, index::Integer) -> UInt64

Returns the seed at the specified index, wrapping around cleanly via modulo if the index exceeds BUNDLE_SIZE.
"""
@inline function seed_at(bundle::SeedBundle, index::Integer)::UInt64
    idx = mod1(index, BUNDLE_SIZE)
    return bundle.seeds[idx]
end

"""
    seeds_range(bundle::SeedBundle, range::AbstractRange) -> Vector{UInt64}

Returns a slice of seeds from the bundle.
"""
function seeds_range(bundle::SeedBundle, range::AbstractRange)::Vector{UInt64}
    return [seed_at(bundle, i) for i in range]
end

